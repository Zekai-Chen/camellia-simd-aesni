static void print_vector(const char *label, int idx, const uint8_t *data) {
    printf("%s[%2d]: ", label, idx);
    for (int i = 0; i < 16; i++) {
        printf("%02x ", data[idx * 16 + i]);
    }
    printf("\n");
}

int main(void) {
    uint8_t plaintext[256];
    uint8_t output[256];

    printf("========================================\n");
    printf("Direct Byteslice Test\n");
    printf("========================================\n\n");

    // Prepare input - 16 identical blocks
    for (int i = 0; i < 16; i++) {
        memcpy(plaintext + i * 16, test_plaintext, 16);
    }

    printf("Input plaintext (first block):\n  ");
    for (int i = 0; i < 16; i++) {
        printf("%02x ", test_plaintext[i]);
    }
    printf("\n\n");

    // Test assembly implementation
    test_byteslice_asm(output, plaintext);

    printf("Assembly output:\n");
    for (int i = 0; i < 16; i++) {
        print_vector("  ", i, output);
    }
    printf("\n");

    // Compare each vector
    printf("Comparison:\n");
    printf("-----------\n");
    int errors = 0;
    for (int vec = 0; vec < 16; vec++) {
        int vec_errors = 0;
        for (int byte = 0; byte < 16; byte++) {
            if (output[vec * 16 + byte] != expected_output[vec * 16 + byte]) {
                vec_errors++;
                errors++;
            }
        }
        if (vec_errors > 0) {
            printf("Vector %2d: %d bytes differ (expected 0x%02x, got mixed)\n",
                   vec, vec_errors, expected_output[vec * 16]);
        } else {
            printf("Vector %2d: OK (all 0x%02x)\n", vec, expected_output[vec * 16]);
        }
    }

    printf("\n");
    if (errors == 0) {
        printf("✓ SUCCESS: Byteslice matches perfectly!\n");
        return 0;
    } else {
        printf("✗ FAILED: %d bytes differ\n", errors);
        return 1;
    }
}
