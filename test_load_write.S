/* Test simple load + write without any transformations */
.text

.global test_load_write_asm
.type test_load_write_asm, %function

// void test_load_write_asm(uint8_t *output, const uint8_t *input)
test_load_write_asm:
    // x0 = output
    // x1 = input

    // Load 16 blocks
    ldp     q0, q1, [x1, #0]
    ldp     q2, q3, [x1, #32]
    ldp     q4, q5, [x1, #64]
    ldp     q6, q7, [x1, #96]
    ldp     q8, q9, [x1, #128]
    ldp     q10, q11, [x1, #160]
    ldp     q12, q13, [x1, #192]
    ldp     q14, q15, [x1, #224]

    // Write 16 blocks back in same order
    stp     q0, q1, [x0, #0]
    stp     q2, q3, [x0, #32]
    stp     q4, q5, [x0, #64]
    stp     q6, q7, [x0, #96]
    stp     q8, q9, [x0, #128]
    stp     q10, q11, [x0, #160]
    stp     q12, q13, [x0, #192]
    stp     q14, q15, [x0, #224]

    ret
